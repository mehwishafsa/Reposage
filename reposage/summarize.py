"""The AI step: plain-English summaries, real layers and tags.

Tree-sitter tells us WHAT is in the code (deterministic facts). This step
adds WHY: a short plain-English summary for each file and its key
functions, the file's architectural layer, and a few topic tags.

The writing is done by Claude (a small, cheap model) following the
instructions in agents/summarizer.md. This module does everything around it:

  plan  -> choose which files need a summary, pack them into batches
           (.reposage/ai/batch-001.md, ...) and estimate the size of the job
  run   -> send each batch to `claude -p` (Haiku, no tools), a few at a
           time, and save every answer as soon as it arrives
  save  -> check one batch's answer (JSON) and merge it into graph.json

Being affordable:
  * incremental: a file is only summarized again when its content changed
    (summaries are kept per file hash; see graph_builder._carry_over_ai_fields)
  * tests and generated code are skipped by default
  * near-empty files get a fixed summary without asking the AI
  * files are batched, and a cheap model (Haiku) does the writing
"""

from __future__ import annotations

import json
import os
import re
import shutil
import subprocess
import threading
import time
from collections import defaultdict
from concurrent.futures import ThreadPoolExecutor, as_completed
from typing import Callable, Optional

from .cache import write_json_atomic
from .layers import LAYERS, TESTS, guess_layer

AI_DIR = "ai"
BATCH_CHARS = 45_000          # ~11k tokens of input per batch
MAX_FILES_PER_BATCH = 10
SOURCE_CHARS = 9_000          # per file: the first ~250 lines of code
MAX_KEY_SYMBOLS = 6           # per file
SUMMARY_LIMIT = 700           # characters, file summaries
SYMBOL_SUMMARY_LIMIT = 300
MAX_TAGS = 4

_GENERATED_DIRS = {"generated", "__generated__", "gen", "vendor", "vendors",
                   "third_party", "thirdparty", "external", "migrations"}
_GENERATED_NAME = re.compile(r"(_pb2(_grpc)?\.py|\.pb\.\w+|\.generated\.\w+|\.g\.\w+|"
                             r"\.min\.js|\.bundle\.js)$", re.I)
_GENERATED_HEADER = re.compile(r"auto-?generated|@generated|do not edit|generated by", re.I)


# ----------------------------------------------------------------------
# plan
# ----------------------------------------------------------------------

def plan(repo: str, graph: dict, include_tests: bool = False, force: bool = False,
         limit: Optional[int] = None) -> dict:
    """Decide what to summarize, write the batch files, return the plan."""
    nodes = graph["nodes"]
    files = [n for n in nodes if n["type"] == "file"]
    symbols_by_file: dict[str, list[dict]] = defaultdict(list)
    for n in nodes:
        if n["type"] != "file":
            symbols_by_file[n["path"]].append(n)
    degree = _degrees(graph)
    links = _file_links(graph)

    todo, skipped = [], defaultdict(list)
    rule_based: dict[str, str] = {}
    for f in files:
        path = f["id"]
        if f.get("summary") and not f.get("ai_stale") and not force:
            skipped["done"].append(path)
            continue
        if guess_layer(path) == TESTS and not include_tests:
            skipped["tests"].append(path)
            continue
        source = _read(os.path.join(repo, path))
        if source is None:
            skipped["unreadable"].append(path)
            continue
        if _is_generated(path, source):
            skipped["generated"].append(path)
            continue
        trivial = _trivial_summary(path, source, symbols_by_file[path])
        if trivial:
            rule_based[path] = trivial
            continue
        todo.append(f)

    # Most connected files first, so `--limit` keeps the important ones.
    todo.sort(key=lambda f: (-degree.get(f["id"], 0), f["id"]))
    if limit is not None and len(todo) > limit:
        skipped["over limit"] = [f["id"] for f in todo[limit:]]
        todo = todo[:limit]

    # Build one text section per file, then pack sections into batches.
    sections = []
    for f in todo:
        path = f["id"]
        keys = _key_symbols(symbols_by_file[path], degree)
        text = _file_section(repo, f, graph, keys, links)
        sections.append({"path": path, "hash": graph["files"][path]["hash"],
                         "symbols": [s["id"] for s in keys], "text": text})

    batches, current, size = [], [], 0
    for sec in sections:
        if current and (size + len(sec["text"]) > BATCH_CHARS
                        or len(current) >= MAX_FILES_PER_BATCH):
            batches.append(current)
            current, size = [], 0
        current.append(sec)
        size += len(sec["text"])
    if current:
        batches.append(current)

    # Write the batches.
    ai_dir = os.path.join(repo, ".reposage", AI_DIR)
    shutil.rmtree(ai_dir, ignore_errors=True)
    os.makedirs(ai_dir)
    project = os.path.basename(os.path.abspath(repo))
    batch_meta = []
    for k, batch in enumerate(batches, start=1):
        name = f"batch-{k:03d}.md"
        header = (f"# RepoSage summary batch {k} of {len(batches)}\n\n"
                  f"Project: **{project}**. Summarize the {len(batch)} file(s) below "
                  f"and answer with ONE JSON object, as described in your instructions. "
                  f"Use `\"batch\": {k}`.\n")
        with open(os.path.join(ai_dir, name), "w", encoding="utf-8", newline="\n") as fh:
            fh.write(header + "\n".join(sec["text"] for sec in batch))
        batch_meta.append({"batch": k, "file": f".reposage/{AI_DIR}/{name}",
                           "files": [{"path": s["path"], "hash": s["hash"], "symbols": s["symbols"]}
                                     for s in batch]})

    # Near-empty files: apply their fixed summary right away.
    if rule_based:
        _merge(repo, {p: {"summary": s} for p, s in rule_based.items()})

    total_chars = sum(len(s["text"]) for s in sections)
    n_symbols = sum(len(s["symbols"]) for s in sections)
    result = {
        "batches": batch_meta,
        "files_to_summarize": len(sections),
        "symbols_to_summarize": n_symbols,
        "rule_based": sorted(rule_based),
        "skipped": {k: sorted(v) for k, v in skipped.items()},
        # ~4 characters per token; plus the agent's instructions for each batch.
        "estimated_input_tokens": total_chars // 4 + 1_200 * len(batches),
        "estimated_output_tokens": 130 * len(sections) + 45 * n_symbols,
    }
    write_json_atomic(os.path.join(ai_dir, "plan.json"), result)
    return result


def print_plan(p: dict) -> None:
    skipped = p["skipped"]
    print("RepoSage summarize: plan")
    print(f"  To summarize   {p['files_to_summarize']} files "
          f"(+ {p['symbols_to_summarize']} key functions/classes) "
          f"in {len(p['batches'])} batch{'es' if len(p['batches']) != 1 else ''}")
    print(f"  Already done   {len(skipped.get('done', []))} files (unchanged since their last summary)")
    parts = [f"{len(skipped.get('tests', []))} test files",
             f"{len(skipped.get('generated', []))} generated/vendored"]
    if skipped.get("over limit"):
        parts.append(f"{len(skipped['over limit'])} over --limit")
    print(f"  Skipped        {', '.join(parts)}")
    if p["rule_based"]:
        print(f"  Near-empty     {len(p['rule_based'])} files got a fixed summary (no AI needed)")
    print(f"  Estimated size ~{p['estimated_input_tokens']:,} input + "
          f"~{p['estimated_output_tokens']:,} output tokens (Haiku agents)")
    for b in p["batches"]:
        print(f"  Batch {b['batch']:>3}      {b['file']}  ({len(b['files'])} files)")
    if not p["batches"]:
        print("  Nothing to do: every file already has an up-to-date summary.")


