# Helpers
# ----------------------------------------------------------------------

def _merge(repo: str, updates: dict[str, dict]) -> tuple[int, list[str]]:
    """Write summaries into graph.json. Skips files whose hash moved on."""
    graph = _load_graph(repo)
    by_id = {n["id"]: n for n in graph["nodes"]}
    saved, stale = 0, []
    for path, up in updates.items():
        node = by_id.get(path)
        if node is None or ("hash" in up and graph["files"].get(path, {}).get("hash") != up["hash"]):
            stale.append(path)
            continue
        node["summary"] = up["summary"]
        node.pop("ai_stale", None)                 # fresh again
        if "layer" in up:
            node["layer"] = up["layer"]
        if "tags" in up:
            node["tags"] = up["tags"]
        for sym_id, text in up.get("symbols", {}).items():
            if sym_id in by_id:
                by_id[sym_id]["summary"] = text
                by_id[sym_id].pop("ai_stale", None)
        saved += 1
    write_json_atomic(os.path.join(repo, ".reposage", "graph.json"), graph)
    return saved, stale


def _load_graph(repo: str) -> dict:
    with open(os.path.join(repo, ".reposage", "graph.json"), encoding="utf-8") as fh:
        return json.load(fh)


def _read(path: str) -> Optional[str]:
    try:
        with open(path, encoding="utf-8", errors="replace") as fh:
            return fh.read()
    except OSError:
        return None


def _is_generated(path: str, source: str) -> bool:
    parts = path.lower().split("/")
    if any(p in _GENERATED_DIRS for p in parts[:-1]) or _GENERATED_NAME.search(parts[-1]):
        return True
    head = "\n".join(source.splitlines()[:5])
    return bool(_GENERATED_HEADER.search(head))


def _trivial_summary(path: str, source: str, symbols: list[dict]) -> Optional[str]:
    """A fixed summary for files with (almost) nothing in them."""
    lines = [ln for ln in source.splitlines()
             if ln.strip() and not ln.strip().startswith(("#", "//", "/*", "*"))]
    if symbols or len(lines) > 3:
        return None
    name = path.rsplit("/", 1)[-1]
    if name == "__init__.py":
        return ("Marks this folder as a Python package so its files can be imported."
                + (" It also re-exports a few names for convenience." if lines else ""))
    if not lines:
        return "An empty file (it may only contain comments)."
    return f"A very small file with {len(lines)} line(s) of setup code."


def _degrees(graph: dict) -> dict[str, int]:
    """Number of calls/imports touching each node (and each file)."""
    deg: dict[str, int] = defaultdict(int)
    for e in graph["edges"]:
        if e["type"] in ("calls", "imports"):
            deg[e["source"]] += 1
            deg[e["target"]] += 1
            fs, ft = e["source"].split("::")[0], e["target"].split("::")[0]
            if e["type"] == "calls" and fs != ft:
                deg[fs] += 1
                deg[ft] += 1
    return deg


def _file_links(graph: dict) -> dict[str, dict[str, set]]:
    uses: dict[str, set] = defaultdict(set)
    used_by: dict[str, set] = defaultdict(set)
    for e in graph["edges"]:
        if e["type"] in ("calls", "imports"):
            s, t = e["source"].split("::")[0], e["target"].split("::")[0]
            if s != t:
                uses[s].add(t)
                used_by[t].add(s)
    return {"uses": uses, "used_by": used_by}


def _key_symbols(symbols: list[dict], degree: dict[str, int]) -> list[dict]:
    """The few classes/functions worth a one-line summary."""
    def score(s: dict) -> tuple:
        private = s["name"].startswith("_") and not s["name"].startswith("__")
        size = s["end_line"] - s["start_line"] + 1
        top_level = 8 if s.get("parent") is None else 0
        return (-(degree.get(s["id"], 0) * 3 + top_level + (5 if s["type"] in ("class", "interface") else 0)
                  + min(size, 60) / 10 - (6 if private else 0)), s["id"])
    candidates = [s for s in symbols
                  if s["end_line"] - s["start_line"] >= 2 or degree.get(s["id"], 0) >= 2]
    return sorted(candidates, key=score)[:MAX_KEY_SYMBOLS]


def _file_section(repo: str, f: dict, graph: dict, keys: list[dict], links: dict) -> str:
    path = f["id"]
    source = _read(os.path.join(repo, path)) or ""
    lines = source.splitlines()
    shown = source[:SOURCE_CHARS]
    cut = len(shown) < len(source)
    if cut:
        shown = shown[: shown.rfind("\n")]
    shown_lines = shown.count("\n") + 1
    outline = sorted((n for n in graph["nodes"] if n.get("path") == path and n["type"] != "file"),
                     key=lambda n: (n["start_line"], n["id"]))
    fence = "~~~~"      # can't clash with ``` inside the code

    def names(paths: set) -> str:
        items = sorted(p.rsplit("/", 1)[-1] for p in paths)
        return ", ".join(items[:12]) + (f" (+{len(items) - 12} more)" if len(items) > 12 else "") or "none"

    out = [f"\n## File: {path}",
           f"- language: {f.get('language')}, {len(lines)} lines",
           f"- layer guessed from its path: {guess_layer(path)}",
           f"- uses: {names(links['uses'].get(path, set()))}",
           f"- used by: {names(links['used_by'].get(path, set()))}"]
    if f.get("external_imports"):
        out.append(f"- external packages: {', '.join(f['external_imports'][:15])}")
    if keys:
        out.append("- key symbols to summarize (copy each id exactly):")
        out += [f"  - id: `{s['id']}` ({s['type']}, line {s['start_line']}): `{s['signature']}`" for s in keys]
    if cut:
        out.append(f"- outline of the whole file ({len(outline)} definitions):")
        out += [f"  - line {s['start_line']}: {s['type']} {s['name']}" for s in outline[:60]]
        out.append(f"\nSource (first {shown_lines} of {len(lines)} lines):")
    else:
        out.append("\nSource:")
    out += [fence, shown, fence]
    return "\n".join(out) + "\n"


def _strip_fences(text: str) -> str:
    text = text.strip()
    m = re.search(r"```(?:json)?\s*(\{.*\})\s*```", text, re.S)
    if m:
        return m.group(1)
    start, end = text.find("{"), text.rfind("}")
    return text[start:end + 1] if start != -1 and end > start else text


def _clean_text(value, limit: int) -> str:
    if not isinstance(value, str):
        return ""
    text = " ".join(value.split())
    return text if len(text) <= limit else text[: limit - 1].rstrip() + "…"
