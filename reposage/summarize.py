def save(repo: str, batch_no: int, answer: str) -> tuple[int, int, list[str]]:
    """Check an agent's answer for one batch and merge it into graph.json.

    Returns (files saved, symbols saved, problems). Problems are reported so
    the batch can be retried; the good parts of an answer are always kept.
    """
    plan_path = os.path.join(repo, ".reposage", AI_DIR, "plan.json")
    with open(plan_path, encoding="utf-8") as fh:
        the_plan = json.load(fh)
    batch = next((b for b in the_plan["batches"] if b["batch"] == batch_no), None)
    if batch is None:
        return 0, 0, [f"there is no batch {batch_no} in the current plan"]
    try:
        data = json.loads(_strip_fences(answer))
    except ValueError as e:
        return 0, 0, [f"the answer is not valid JSON ({e})"]
    if not isinstance(data, dict) or not isinstance(data.get("files"), list):
        return 0, 0, ['expected an object like {"batch": N, "files": [...]}']

    expected = {f["path"]: f for f in batch["files"]}
    updates: dict[str, dict] = {}
    problems: list[str] = []
    answered: set[str] = set()      # files the answer mentioned (even if invalid)
    n_symbols = 0
    for item in data["files"]:
        if not isinstance(item, dict):
            continue
        path = item.get("path")
        if path not in expected:
            problems.append(f"unknown file in answer: {path!r}")
            continue
        answered.add(path)
        summary = _clean_text(item.get("summary"), SUMMARY_LIMIT)
        if not summary:
            problems.append(f"{path}: empty summary")
            continue
        layer = item.get("layer")
        if layer not in LAYERS:
            problems.append(f"{path}: layer {layer!r} is not one of {', '.join(LAYERS)}; kept the guess")
            layer = None
        tags = [re.sub(r"[^a-z0-9+#.-]+", "-", str(t).lower()).strip("-")
                for t in (item.get("tags") or []) if str(t).strip()][:MAX_TAGS]
        update = {"summary": summary, "tags": tags, "hash": expected[path]["hash"]}
        if layer:
            update["layer"] = layer
        allowed = set(expected[path]["symbols"])
        sym_updates = {}
        for sym in item.get("symbols") or []:
            if isinstance(sym, dict) and sym.get("id") in allowed:
                text = _clean_text(sym.get("summary"), SYMBOL_SUMMARY_LIMIT)
                if text:
                    sym_updates[sym["id"]] = text
        update["symbols"] = sym_updates
        n_symbols += len(sym_updates)
        updates[path] = update
    missing = sorted(set(expected) - answered)
    problems += [f"{p}: missing from the answer" for p in missing]

    saved, stale = _merge(repo, updates)
    problems += [f"{p}: file changed since the plan; run the plan again" for p in stale]
    return saved, n_symbols, problems


def progress(repo: str) -> tuple[int, int]:
    """(files in the plan that now have a summary, files in the plan)."""
    with open(os.path.join(repo, ".reposage", AI_DIR, "plan.json"), encoding="utf-8") as fh:
        the_plan = json.load(fh)
    planned = {f["path"] for b in the_plan["batches"] for f in b["files"]}
    graph = _load_graph(repo)
    done = sum(1 for n in graph["nodes"] if n["id"] in planned and n.get("summary"))
    return done, len(planned)


