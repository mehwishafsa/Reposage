AGENT_PROMPT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                            "agents", "summarizer.md")


def run(repo: str, model: str = "haiku", parallel: int = 4, timeout: int = 300,
        say: Callable[[str], None] = print) -> dict:
    """Summarize every batch of the current plan that isn't saved yet.

    Each batch goes to a separate `claude -p` process: no tools, a short
    system prompt (agents/summarizer.md), the batch as the message. Answers
    are saved as they arrive, so an interrupted run can simply be started
    again and continues where it stopped.
    """
    claude = os.environ.get("REPOSAGE_CLAUDE") or shutil.which("claude")
    if not claude:
        raise RuntimeError("the `claude` command was not found. RepoSage uses Claude Code "
                           "to write summaries; install it from https://claude.com/claude-code")
    with open(os.path.join(repo, ".reposage", AI_DIR, "plan.json"), encoding="utf-8") as fh:
        the_plan = json.load(fh)
    system_prompt = _agent_instructions()
    todo = [b for b in the_plan["batches"] if not _batch_done(repo, b)]
    if not todo:
        say("All batches are already saved.")
        return {"batches": 0, "files": 0, "symbols": 0, "cost_usd": 0.0, "failed": []}

    def ask(batch: dict) -> tuple[str, float]:
        with open(os.path.join(repo, batch["file"]), encoding="utf-8") as fh:
            message = fh.read()
        proc = subprocess.run(
            [claude, "-p", "--model", model, "--tools", "", "--output-format", "json",
             "--system-prompt", system_prompt, "--no-session-persistence",
             "--strict-mcp-config", "--disable-slash-commands"],
            input=message, capture_output=True, text=True, timeout=timeout)
        try:
            out = json.loads(proc.stdout)
        except ValueError:
            raise RuntimeError((proc.stderr or proc.stdout or "no output").strip()[:300])
        if out.get("is_error"):
            raise RuntimeError(str(out.get("result"))[:300])
        return out.get("result", ""), float(out.get("total_cost_usd") or 0)

    totals = {"batches": 0, "files": 0, "symbols": 0, "cost_usd": 0.0, "failed": []}
    total_batches = len(the_plan["batches"])
    graph_lock = threading.Lock()      # one writer of graph.json at a time

    def work(batch: dict) -> tuple[dict, int, int, list[str], float, float]:
        started, cost, problems = time.time(), 0.0, []
        files = symbols = 0
        for attempt in (1, 2):                        # one retry if something is missing
            try:
                answer, c = ask(batch)
                cost += c
                with graph_lock:
                    f, s_, problems = save(repo, batch["batch"], answer)
                files, symbols = files + f, symbols + s_
            except (RuntimeError, subprocess.TimeoutExpired, OSError) as e:
                problems = [f"Claude call failed: {e}"]
            with graph_lock:
                if _batch_done(repo, batch):
                    break
        return batch, files, symbols, problems, cost, time.time() - started

    say(f"Summarizing {len(todo)} batch(es) with {model}, {min(parallel, len(todo))} at a time...")
    with ThreadPoolExecutor(max_workers=max(1, parallel)) as pool:
        futures = [pool.submit(work, b) for b in todo]
        for fut in as_completed(futures):
            batch, files, symbols, problems, cost, secs = fut.result()
            ok = _batch_done(repo, batch)
            totals["batches"] += 1
            totals["files"] += files
            totals["symbols"] += symbols
            totals["cost_usd"] += cost
            say(f"  batch {batch['batch']}/{total_batches}: {files} files, {symbols} functions/classes"
                f" {'✓' if ok else '(incomplete)'}  ${cost:.3f}, {secs:.0f}s")
            if not ok:
                totals["failed"].append(batch["batch"])
                for p in problems[:5]:
                    say(f"      problem: {p}")
    done, planned = progress(repo)
    say(f"Done: {done} of {planned} planned files have a summary. "
        f"Cost of this run: ${totals['cost_usd']:.2f}.")
    if totals["failed"]:
        say(f"Incomplete batches: {totals['failed']}. Run `summarize run` again to retry them.")
    return totals


def _agent_instructions() -> str:
    """The body of agents/summarizer.md (without its frontmatter)."""
    with open(AGENT_PROMPT, encoding="utf-8") as fh:
        text = fh.read()
    if text.startswith("---"):
        text = text.split("---", 2)[2]
    return text.strip()


def _batch_done(repo: str, batch: dict) -> bool:
    """True when every file of the batch has a summary for its planned hash."""
    graph = _load_graph(repo)
    by_id = {n["id"]: n for n in graph["nodes"]}
    for f in batch["files"]:
        node = by_id.get(f["path"])
        if (node is None or not node.get("summary") or node.get("ai_stale")
                or graph["files"].get(f["path"], {}).get("hash") != f["hash"]):
            return False
    return True


